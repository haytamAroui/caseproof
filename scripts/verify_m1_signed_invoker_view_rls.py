"""Disposable Postgres 17 RLS acceptance for invoker views; NOT signed Auth.

Only runs in the existing pinned ephemeral localhost CI DB. Authentic Supabase
PostgREST JWT verification is a separate protected integration gate. Do not
point to live DB or issue SQL claims there.
"""
from __future__ import annotations

from pathlib import Path
from uuid import uuid4

from scripts.verify_m1_private_rls import seed
from scripts.verify_s2_002_database import MIGRATION, SCHEMA_BOOTSTRAP, _env, _run
from scripts.verify_vault_integration import connect

ROOT = Path(__file__).resolve().parents[1]
M1 = ROOT / "db/proposals/PIV-M1_DEV_atomic_private_grant_install.sql"
API = ROOT / "db/proposals/PIV-M1_signed_invoker_read_api_candidate.sql"


def _local() -> dict[str, str]:
    env = _env()
    if (
        env.get("PGHOST") != "127.0.0.1"
        or env.get("PGPORT") != "5432"
        or any(item in env for item in ("PGHOSTADDR", "PGSERVICE", "PGOPTIONS"))
    ):
        raise RuntimeError("only isolated PostgreSQL CI service is supported")
    return env


def _visible(env: dict[str, str], actor: str | None, relation: str) -> int:
    if relation not in {
        "caseproof_private_matters", "caseproof_private_source_versions",
    }:
        raise AssertionError("unapproved relation")
    claim = (
        f"set local request.jwt.claim.sub='{actor}'; "
        if actor is not None else ""
    )
    return int(_run(
        "begin; set local role authenticated; " + claim
        + f"select count(*) from public.{relation}; commit;", env,
    ))


def _case_visible(env: dict[str, str], actor: str, case: str) -> bool:
    # UUID inputs are generated by controlled local fixture, not user SQL.
    return _run(
        "begin; set local role authenticated; "
        f"set local request.jwt.claim.sub='{actor}'; "
        "select exists(select 1 from public.caseproof_private_matters "
        f"where case_id='{case}'); commit;", env,
    ) == "t"


def _assert_no_view(env: dict[str, str]) -> None:
    if _run(
        "select count(*) from pg_class c join pg_namespace n "
        "on n.oid=c.relnamespace where n.nspname='public' "
        "and c.relname in ('caseproof_private_matters',"
        "'caseproof_private_source_versions')", env,
    ) != "0":
        raise AssertionError("failed transaction created a public API view")


def _assert_view_security(env: dict[str, str]) -> None:
    views = _run(
        "select count(*) from pg_class c join pg_namespace n "
        "on n.oid=c.relnamespace where n.nspname='public' "
        "and c.relname in ('caseproof_private_matters',"
        "'caseproof_private_source_versions') and c.relkind='v' "
        "and 'security_invoker=true'=any(c.reloptions) "
        "and 'security_barrier=true'=any(c.reloptions)", env,
    )
    if views != "2":
        raise AssertionError("view owner would bypass expected RLS")
    for relation in ("caseproof_private_matters", "caseproof_private_source_versions"):
        for command in (
            f"select * from public.{relation}",
            f"update public.{relation} set org_id='{uuid4()}'",
            f"delete from public.{relation}",
        ):
            _run(f"set role anon; {command}", env, should_pass=False)
        for command in (
            f"update public.{relation} set org_id='{uuid4()}'",
            f"delete from public.{relation}",
        ):
            _run(f"set role authenticated; {command}", env, should_pass=False)


def main() -> None:
    env = _local()
    if _run("select to_regclass('caseproof.cases') is null", env) != "t":
        raise RuntimeError("fresh disposable database required")
    _run("begin;\n" + SCHEMA_BOOTSTRAP + MIGRATION.read_text()
         + "\ncommit;", env)
    sql = API.read_text(encoding="utf-8")
    # M1 private table/role not installed: no public API views.
    _run(sql, env, should_pass=False)
    _assert_no_view(env)

    _run(M1.read_text(encoding="utf-8"), env)
    # Malicious overlapping SELECT using another table's permitted name.
    _run(
        "create policy m1_private_document_read on caseproof.cases "
        "for select to authenticated using(true)", env,
    )
    _run(sql, env, should_pass=False)
    _assert_no_view(env)
    _run("drop policy m1_private_document_read on caseproof.cases", env)

    _run(sql, env)
    _assert_view_security(env)
    # A second install is not allowed to overwrite a reviewed API contract.
    _run(sql, env, should_pass=False)
    _assert_view_security(env)

    a = seed()
    b = seed(org=a.org)
    c = seed()
    for f in (a, b, c):
        actor, case = str(f.actor), str(f.case)
        if _visible(env, actor, "caseproof_private_matters") != 1:
            raise AssertionError("authorized actor missing exact private case")
        if _visible(env, actor, "caseproof_private_source_versions") != 1:
            raise AssertionError("authorized actor missing exact source version")
        if not _case_visible(env, actor, case):
            raise AssertionError("authorized exact case invisible")
    if _case_visible(env, str(a.actor), str(b.case)):
        raise AssertionError("same-org ungranted case visible")
    if _case_visible(env, str(a.actor), str(c.case)):
        raise AssertionError("foreign-org case visible")
    for relation in ("caseproof_private_matters", "caseproof_private_source_versions"):
        if _visible(env, str(uuid4()), relation) != 0:
            raise AssertionError("ungranted user accessed private view")
        if _visible(env, None, relation) != 0:
            raise AssertionError("unset PostgREST JWT actor accessed view")

    # Org action controls evidence separately. Case remains readable.
    with connect() as conn:
        conn.execute(
            "update caseproof.organization_members "
            "set actions=array['case:read']::text[] "
            "where org_id=%s and user_id=%s", (a.org, a.actor),
        )
    if _visible(env, str(a.actor), "caseproof_private_matters") != 1:
        raise AssertionError("evidence revocation removed allowed case")
    if _visible(env, str(a.actor), "caseproof_private_source_versions") != 0:
        raise AssertionError("revoked evidence action still exposed version")

    # Exact matter grant revocation makes both views empty.
    with connect() as conn:
        conn.execute(
            "update caseproof._m1_matter_grants "
            "set active=false, revision=revision+1 "
            "where org_id=%s and case_id=%s and user_id=%s",
            (b.org, b.case, b.actor),
        )
    for relation in ("caseproof_private_matters", "caseproof_private_source_versions"):
        if _visible(env, str(b.actor), relation) != 0:
            raise AssertionError("revoked matter grant still visible")

    with connect() as conn:
        conn.execute(
            "update caseproof.organization_members "
            "set active=false, membership_revision=membership_revision+1 "
            "where org_id=%s and user_id=%s", (c.org, c.actor),
        )
    if _visible(env, str(c.actor), "caseproof_private_matters") != 0:
        raise AssertionError("revoked org member still reads case")
    print("M1_SECURITY_INVOKER_VIEW_DEFAULT_PRIVATE_RLS_REVOCATION_PASSED")
    print("DISPOSABLE_SQL_CLAIMS_ONLY: NO_SIGNED_AUTH_OR_LIVE_DB_ACCEPTANCE")


if __name__ == "__main__":
    main()
