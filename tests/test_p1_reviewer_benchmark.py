def make_gold(manifest: dict[str, object]) -> dict[str, object]:
    entries = []
    for case in manifest["cases"]:
        entries.append({
            "case_id": case["case_id"],
            "source_version_id": case["source_version_id"],
            "source_sha256": case["source_sha256"],
            "physical_pdf_page": case["physical_pdf_page"],
            "independent_labels": [
                {
                    "adjudicator_pseudonym": name,
                    "decision": "CONTRADICTED",
                    "source_rationale": "Synthetic label generated by test fixture only.",
                }
                for name in ("labeler-one", "labeler-two")
            ],
        })
    return {"schema": GOLD_SCHEMA, "cases": entries}


def make_submissions(
    manifest: dict[str, object],
    *,
    mismatch_for_standard: bool = True,
) -> dict[str, object]:
    decisions = []
    for assignment in manifest["assignments"]:
        wrong = assignment["condition"] == "standard_interface" and mismatch_for_standard
        decisions.append({
            **{k: assignment[k] for k in (
                "assignment_id", "reviewer_id", "case_ref", "condition",
                "source_version_id", "source_sha256", "physical_pdf_page"
            )},
            "decision": "SUPPORTED" if wrong else "CONTRADICTED",
            "elapsed_ms": 20000 if wrong else 24000,
            "inspected_original": True,
            "rationale": "Synthetic, not a real lawyer's source analysis.",
            "confidence": 4,
            "warning_helpful": True if assignment["condition"] == "guarded_term_warnings" else None,
        })
    return {"schema": SUBMISSIONS_SCHEMA, "decisions": decisions}


def test_two_arm_packets_blind_author_seed_and_keep_source_identities() -> None:
    packets, manifest = make_blinded_packets(cases(), REVIEWERS, seed="synthetic-test-seed-1")
    assert manifest["schema"] == ASSIGNMENTS_SCHEMA
    assert manifest["balanced_for_descriptive_arm_comparison"] is True
    assert manifest["assignment_count"] == 8
    assert manifest["reviewer_count"] == 4
    assert {p["condition"] for p in packets} == {
        "standard_interface", "guarded_term_warnings"
    }
    for packet in packets:
        assert packet["schema"] == PACKET_SCHEMA
        assert packet["status"] == "AWAITING_REAL_HUMAN_DECISIONS"
        assert packet["source_inspection_required"] is True
        assert len(packet["cases"]) == 2
        for case in packet["cases"]:
            assert case["case_ref"].startswith("CASE-")
            assert case["source_version_id"] in {"source-nl-v2", "source-fr-v3"}
            assert case["physical_pdf_page"] in (2, 3)
            if packet["condition"] == "standard_interface":
                assert case["guarded_term_warnings"] == []
                assert case["guard_notice"] is None
            else:
                assert case["guarded_term_warnings"]
                assert "no automatic support" in case["guard_notice"].lower()
    serial = json.dumps(packets)
    assert "author_seeded_error" not in serial
    assert "not_for_participants" not in serial
    assert "nl-wrong-version" not in serial
    assert "fr-amount-drift" not in serial
    assert "labeler-one" not in serial


def test_randomization_reproducible_but_case_order_varies_with_seed() -> None:
    a = make_blinded_packets(cases(), REVIEWERS, seed="synthetic-seed-a")
    assert a == make_blinded_packets(cases(), REVIEWERS, seed="synthetic-seed-a")
    b = make_blinded_packets(cases(), REVIEWERS, seed="synthetic-seed-b")
    assert a[1]["assignment_seed_sha256"] != b[1]["assignment_seed_sha256"]
    assert a[1]["assignments"] != b[1]["assignments"]


def test_descriptive_scoring_never_claims_causation_or_authenticated_humans() -> None:
    _, manifest = make_blinded_packets(cases(), REVIEWERS, seed="synthetic-seed")
    result = score_completed_trial(manifest, make_gold(manifest), make_submissions(manifest))
    assert result["schema"] == RESULTS_SCHEMA
    assert result["conditions"]["standard_interface"]["false_confirmations"] == 4
    assert result["conditions"]["standard_interface"]["false_confirmation_rate"] == 1.0
    assert result["conditions"]["guarded_term_warnings"]["false_confirmation_rate"] == 0.0
    assert result["conditions"]["guarded_term_warnings"]["warning_helpful_share"] == 1.0
    assert result["conditions"]["standard_interface"]["missed_contradiction_rate"] == 1.0
    assert result["conditions"]["guarded_term_warnings"]["missed_contradiction_rate"] == 0.0
    assert result["false_confirmation_rate_difference_standard_minus_guarded"] == 1.0
    assert result["identity_and_time_independently_authenticated"] is False
    assert result["gold_adjudicators_independently_authenticated"] is False
    assert result["causal_effect_established"] is False
    assert result["nli_tested"] is False


def test_incomplete_or_duplicate_submissions_cannot_be_scored() -> None:
    _, manifest = make_blinded_packets(cases(), REVIEWERS, seed="synthetic-seed")
    gold = make_gold(manifest)
    submissions = make_submissions(manifest)
    submissions["decisions"].pop()
    with pytest.raises(BenchmarkInvalid, match="full assignment census"):
        score_completed_trial(manifest, gold, submissions)
    submissions = make_submissions(manifest)
    submissions["decisions"][1] = copy.deepcopy(submissions["decisions"][0])
    with pytest.raises(BenchmarkInvalid, match="duplicate or unassigned"):
        score_completed_trial(manifest, gold, submissions)


