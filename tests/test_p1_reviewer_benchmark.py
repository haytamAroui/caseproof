def test_nonindependent_or_mismatched_gold_cannot_be_scored() -> None:
    _, manifest = make_blinded_packets(cases(), REVIEWERS, seed="synthetic-seed")
    submissions = make_submissions(manifest)
    gold = make_gold(manifest)
    gold["cases"][0]["independent_labels"][1]["adjudicator_pseudonym"] = "labeler-one"
    with pytest.raises(BenchmarkInvalid, match="duplicate adjudicator"):
        score_completed_trial(manifest, gold, submissions)
    gold = make_gold(manifest)
    gold["cases"][0]["source_sha256"] = "f" * 64
    with pytest.raises(BenchmarkInvalid, match="source identity"):
        score_completed_trial(manifest, gold, submissions)
    gold = make_gold(manifest)
    gold["cases"][0]["independent_labels"][1]["decision"] = "QUALIFIED"
    with pytest.raises(BenchmarkInvalid, match="disagreement"):
        score_completed_trial(manifest, gold, submissions)


